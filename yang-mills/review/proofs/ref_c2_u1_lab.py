"""Referee C2 -- BEWIJZEN.md section 5.3: "het bewijs werkt ook voor U(1)" and
"hetzelfde bewijs [van stelling A] geldt voor U(1)".

Laboratory: the finite subgroups Z_n of U(1) (n = 5, 8, 12; n = 5 has no element -1), with the
U(1) weight exp(beta * sum_p Re U_p)  (per plaquette in [-beta, beta], like (beta/2) Tr for SU(2)).
D = 2, ring of L = 3 links, T = K P exactly as in section 2.2 with k(h) = exp(beta Re h).

Checked:
  * the structural statements of Stelling A: T symmetric, positive semidefinite, T = PT = TP,
    lambda_0 simple with a strictly positive eigenvector, lambda_1 < lambda_0;
  * the spectrum against the closed form  lambda_j = (c_j)^L,
    c_j = (1/n) sum_k exp(beta cos(2 pi k/n)) cos(2 pi j k/n)   (n -> infinity: I_j(beta));
  * the gap against the bound of Stelling C, point 2 (D = 2): m >= ln(1/(6 tanh beta));
  * the positive-definiteness mechanism of step 3 for U(1): exp(beta Re(u conj(u'))) expands in
    the monomials generated by u AND conj(u) (for U(1), (G2) of section 1.1 does not hold as
    stated: conj(u) is not +- a matrix element of u, so conj(u_e) has to be added to the
    generators); here checked as: all Fourier coefficients c_j of k are > 0.

Run:  python3 review/proofs/ref_c2_u1_lab.py      (from yang-mills/; about 5 s)
"""
import itertools
import math

import numpy as np
from scipy.special import iv


def lab(n, L, beta):
    z = np.exp(2j * np.pi * np.arange(n) / n)
    conf = np.array(list(itertools.product(range(n), repeat=L)))        # exponents
    nC = len(conf)
    code = conf @ (n ** np.arange(L - 1, -1, -1))
    # K(u,u') = prod_e exp(beta Re(u_e conj(u'_e))), normalised counting measure
    diff = (conf[:, None, :] - conf[None, :, :]) % n
    K = np.exp(beta * np.cos(2 * np.pi * diff / n).sum(axis=2)) / nC
    # P: (u^g)_i = g_i u_i g_{i+1}^{-1}
    P = np.zeros((nC, nC))
    for g in conf:
        ug = (conf + g[None, :] - np.roll(g, -1)[None, :]) % n
        idx = ug @ (n ** np.arange(L - 1, -1, -1))
        P[np.arange(nC), idx] += 1.0 / nC
    T = K @ P
    sym = np.abs(T - T.T).max()
    comm = max(np.abs(P @ T - T).max(), np.abs(T @ P - T).max())
    lam, vec = np.linalg.eigh((T + T.T) / 2)
    order = np.argsort(lam)[::-1]
    lam, vec = lam[order], vec[:, order]
    om = vec[:, 0] * np.sign(vec[:, 0].sum())
    cj = np.array([np.mean(np.exp(beta * np.cos(2 * np.pi * np.arange(n) / n)) * np.cos(2 * np.pi * j * np.arange(n) / n))
                   for j in range(n)])
    closed = np.sort(cj ** L)[::-1]
    return dict(sym=sym, comm=comm, lam=lam, minlam=lam.min(), om_min=om.min(), om_max=om.max(),
                closed=closed, cj=cj, rank=int((lam > 1e-13).sum()))


if __name__ == "__main__":
    L = 3
    ok = True
    print("  n   beta    |T-T^T|  |PT-T|   min eig     rank  lambda_0     lambda_1     max|lam-closed|  min c_j     Omega>0  gap m     "
          "L ln(I0/I1) [U(1)]  bound    m>=bound")
    for n in (5, 8, 12):
        for beta in (0.05, 0.10, 0.168):
            r = lab(n, L, beta)
            lam = r["lam"]
            m = math.log(lam[0] / lam[1])
            b = math.log(1 / (6 * math.tanh(beta)))
            dev = np.abs(lam[:n] - r["closed"]).max()
            good = (r["sym"] < 1e-13 and r["comm"] < 1e-13 and r["minlam"] > -1e-13 and dev < 1e-13 and r["cj"].min() > 0
                    and r["om_min"] > 0 and lam[1] < lam[0] * (1 - 1e-9) and m >= b)
            ok &= good
            print(f"  {n:2d}  {beta:5.3f}   {r['sym']:.0e}    {r['comm']:.0e}   {r['minlam']:+.1e}   {r['rank']:3d}   {lam[0]:.8f}   {lam[1]:.4e}   "
                  f"{dev:.1e}          {r['cj'].min():.2e}   {r['om_min'] > 0}     {m:8.4f}  {L*math.log(iv(0,beta)/iv(1,beta)):8.4f}            "
                  f"{b:7.4f}  {m >= b}")
    print("  all checks passed:", ok)
