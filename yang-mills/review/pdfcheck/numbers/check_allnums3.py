#!/usr/bin/env python3
"""All digit strings and all running text of REPORT.md against the PDF body (pages 3, 6-30), using pdfium text
(keeps hyphens at line ends) and pdftotext; ordered-list numbers are generated by the browser and are added to the
Markdown side."""
import re, collections, subprocess, unicodedata, difflib, sys
from html.parser import HTMLParser
import pypdfium2 as pdfium
QA="/tmp/claude-0/-home-user-frisoj/c2e79863-26e2-54ce-9b2d-e39a90258140/scratchpad/qa"
ROOT="/home/user/frisoj/yang-mills"
md=open(ROOT+"/REPORT.md",encoding="utf-8").read()
md2=re.sub(r"\n\$\$\n(.*?)\n\$\$\n","\n\n",md,flags=re.S)
keep=[]; head=True
for ln in md2.split("\n"):
    if ln.startswith("## 0. "): head=False
    if head and (ln.startswith("# ") or ln.startswith("**SU(2)-roostersimulaties") or ln.strip()=="---"): continue
    keep.append(ln)
html=subprocess.run(["pandoc","-f","gfm","-t","html5","--columns=100000"],input="\n".join(keep),capture_output=True,text=True,check=True).stdout
class X(HTMLParser):
    def __init__(s): super().__init__(convert_charrefs=True); s.out=[]; s.stack=[]; s.markers=[]; s.blocks=[]; s.cur=None; s.pre=0
    def handle_starttag(s,tag,attrs):
        a=dict(attrs)
        if tag=="ol": s.stack.append(["ol",int(a.get("start",1))])
        elif tag=="ul": s.stack.append(["ul",0])
        elif tag=="li" and s.stack and s.stack[-1][0]=="ol":
            s.markers.append(str(s.stack[-1][1])); s.stack[-1][1]+=1
        if tag=="pre": s.pre+=1
        if tag in("p","li","h1","h2","h3","h4","pre","td","th","blockquote"): s.blocks.append([]); 
    def handle_endtag(s,tag):
        if tag in("ol","ul") and s.stack: s.stack.pop()
        if tag=="pre": s.pre-=1
    def handle_data(s,d):
        s.out.append(d)
        if s.blocks:
            if s.pre:
                # code lines are painted token by token; compare them line by line without the comment
                s.blocks[-1].append(d)
            else: s.blocks[-1].append(d)
x=X(); x.feed(html)
mdtext="".join(x.out).replace("Bijlage: herkomst van de getallen","Bijlage A: herkomst van de getallen")
pdf=pdfium.PdfDocument(QA+"/REPORT_v1.pdf")
foot=re.compile(r"^Yang–Mills en de massakloof · numeriek bewijsmateriaal, geen bewijs\s*$|^pagina \d+ van \d+\s*$|^Yang–Mills en de massakloof · numeriek bewijsmateriaal, geen bewijs\s*pagina \d+ van \d+$")
def body_of(pages):
    return "\n".join(l for i in [2]+list(range(5,30)) for l in pages[i].replace("\r","").split("\n") if not foot.match(l.strip()))
pf=[pdf[i].get_textpage().get_text_range() for i in range(len(pdf))]
hy=sum(p.count("\x02")+p.count("￾") for p in pf)
pf=[p.replace("\x02","-").replace("￾","-") for p in pf]
bodies={"pdfium":body_of(pf), "pdftotext raw":body_of(open(QA+"/numverify/pdf_raw.txt",encoding="utf-8").read().split("\f"))}
print("ordered-list items in REPORT.md (numbers generated by the browser):", len(x.markers), "| line-end hyphen markers in pdfium text:", hy)
NUM=re.compile(r"\d+(?:[.,]\d+)*")
n=lambda t: re.sub(r"\s+","",unicodedata.normalize("NFC",t).replace(" "," "))
for name,body in bodies.items():
    body=body.replace("Vooraf en leeswijzer","",1)
    a=collections.Counter(NUM.findall(mdtext)); a.update(x.markers); b=collections.Counter(NUM.findall(body))
    print(f"\n[{name}] digit strings: REPORT.md %d occurrences (%d distinct); PDF body %d occurrences (%d distinct)"%(sum(a.values()),len(a),sum(b.values()),len(b)))
    print("  fewer in PDF (md, pdf):", {k:(v,b.get(k,0)) for k,v in a.items() if b.get(k,0)<v})
    print("  fewer in REPORT.md (md, pdf):", {k:(a.get(k,0),v) for k,v in b.items() if a.get(k,0)<v})
    wa=collections.Counter(n(mdtext)+"".join(m+"." for m in x.markers)); wb=collections.Counter(n(body))
    diff={k:(wa.get(k,0),wb.get(k,0)) for k in set(wa)|set(wb) if wa.get(k,0)!=wb.get(k,0)}
    print("  characters (whitespace-free): REPORT.md %d, PDF body %d; characters with different counts (md, pdf): %s"%(sum(wa.values()),sum(wb.values()),diff))
    flat=n(body)
    blocks=[n("".join(b)) for b in x.blocks]; blocks=[b.replace("Bijlage:herkomstvandegetallen","BijlageA:herkomstvandegetallen") for b in blocks if b]
    miss=[p for p in blocks if p not in flat]
    print("  text blocks of REPORT.md (paragraphs, list items, headings, table cells, code blocks): %d; found verbatim in the PDF text: %d"%(len(blocks),len(blocks)-len(miss)))
    for p in miss[:12]:
        sm=difflib.SequenceMatcher(None,p,flat,autojunk=False); m=sm.find_longest_match(0,len(p),0,len(flat))
        print("     not verbatim (%d chars, longest common run %d): %s"%(len(p),m.size,p[:90]))
        print("        md : ...%s"%p[max(0,m.a+m.size-30):m.a+m.size+50]); print("        pdf: ...%s"%flat[max(0,m.b+m.size-30):m.b+m.size+50])
